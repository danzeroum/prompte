let currentLang = 'pt';

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  currentLang = DICT[lang] ? lang : 'pt';
  setPreference('lang', currentLang);
  document.documentElement.setAttribute('lang', currentLang === 'pt' ? 'pt-BR' : 'en');
  applyI18n();
  return currentLang;
}

// Traduz uma chave; cai no português e, por fim, na própria chave.
export function t(key, lang = currentLang) {
  return (DICT[lang] && DICT[lang][key]) || DICT.pt[key] || key;
}

// Aplica traduções a todos os elementos [data-i18n] dentro de root.
// - data-i18n            → textContent
// - data-i18n + data-i18n-attr → atributo nomeado (ex.: placeholder, title)
// - data-i18n-html       → innerHTML (blocos com marcação inline, ex.: <strong>)
// Ao final dispara o evento `pe:i18n` para que decorações dependentes de texto
// (ex.: o glossário inline) possam se re-renderizar (#M-UX6).
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const attr = el.getAttribute('data-i18n-attr');
    const value = t(key);
    if (attr) el.setAttribute(attr, value);
    else el.textContent = value;
  });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });
  const Evt = typeof globalThis !== 'undefined' ? globalThis.CustomEvent : null;
  if (Evt && typeof document !== 'undefined' && typeof document.dispatchEvent === 'function') {
    document.dispatchEvent(new Evt('pe:i18n', { detail: { lang: currentLang } }));
  }
}

export function initI18n() {
  currentLang = getPreferences().lang || 'pt';
  if (!DICT[currentLang]) currentLang = 'pt';
  document.documentElement.setAttribute('lang', currentLang === 'pt' ? 'pt-BR' : 'en');
  applyI18n();
}
